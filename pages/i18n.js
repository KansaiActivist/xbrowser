function setLang(l) {
  LANG = LANGS.indexOf(l) >= 0 ? l : 'ja';
  document.documentElement.lang = LANG;
}

function t(key) {
  var v = STR[key];
  var s = v ? (v[LANGS.indexOf(LANG)] || v[1]) : key;
  for (var i = 1; i < arguments.length; i++) s = s.split('{' + (i - 1) + '}').join(arguments[i]);
  return s;
}
